/**
 * Durable chat-bench turn receipts (attribution design f5d77712 revision 10
 * section 3.4, writer "chat bench"; receipt location decided by luca-replit
 * on coordination thread dd40f2cf, sequence 524).
 *
 * The receipt is the bench session's existing conversation_memories row,
 * created durably at the first captured turn. Each turn appends an immutable,
 * byte-verified exchange event (source "holahola-chat-bench", sourceEventId
 * "<sessionId>:<turnId>", frames "luca" and, when Daniela produced text,
 * "daniela") through the common append. The growing row is never itself a
 * completed-turn receipt; only the frames of one event are.
 *
 * Identity scope: sessionId is caller-generated and owned by the user that
 * created the session row (a different user reusing it is refused). turnId
 * is caller-generated and unique within its session. Neither may come from
 * Date.now() fallbacks or the in-memory turn counter.
 *
 * Exactly-once boundary, stated plainly: the receipt commits AFTER Daniela's
 * reply exists. A crash after the model call but before the receipt commits
 * leaves no receipt, and a retry runs Daniela again. A completed receipt
 * makes every later exact retry return the stored bytes without rerunning
 * Daniela or tools. Provider-side exactly-once execution is NOT claimed.
 *
 * Hat: the bench route authenticates an admin web session. That is not
 * evidence of a Luca hat, so frames record hat "unknown" (evidence "none").
 *
 * Visibility of an unfinished session row: text readers of
 * conversation_memories (title/content/tag queries) can see it from the
 * first turn; it carries the "in-progress" tag until endSession or expiry
 * finalizes it. Embedding happens only at finalization, exactly as before;
 * there is no per-turn embedding.
 */
import { sql } from 'drizzle-orm';
import { applyProjectionAppendInTx, rowsOf, type SqlExecutor, type TransactionalDb } from './projection-append-store';
import type { AppendEvent } from './projection-append';
import { turnAttributionOf, verifyTurnAttribution } from './turn-attribution';

export const BENCH_SOURCE = 'holahola-chat-bench';
const IDENTITY = /^[A-Za-z0-9._-]{8,80}$/;
export const IN_PROGRESS_TAG = 'in-progress';

/**
 * A text[] parameter. drizzle's sql template expands a JS array into a list
 * of separate parameters, so arrays travel as one JSON parameter instead.
 */
const textArray = (values: string[]) =>
  sql`ARRAY(SELECT jsonb_array_elements_text(${JSON.stringify(values)}::jsonb))::text[]`;

export const sessionTag = (sessionId: string) => `bench-session:${sessionId}`;
export const ownerTag = (userId: string) => `bench-owner:${userId}`;
export const benchEventId = (sessionId: string, turnId: string) => `${sessionId}:${turnId}`;

/** Reject missing/invalid identity before any model or tool side effect. */
export function validateBenchIdentity(sessionId: unknown, turnId: unknown): string | null {
  if (typeof sessionId !== 'string' || !IDENTITY.test(sessionId)) return 'sessionId must be 8-80 characters of [A-Za-z0-9._-], generated by the caller';
  if (typeof turnId !== 'string' || !IDENTITY.test(turnId)) return 'turnId must be 8-80 characters of [A-Za-z0-9._-], generated by the caller and unique within the session';
  return null;
}

export interface BenchTurn {
  sessionId: string;
  turnId: string;
  /** Exact text Luca sent (the request's studentText), never trimmed. */
  lucaText: string;
  /** Daniela's reply text exactly as the route assembled it; '' when none. */
  danielaText: string;
  /** "daniela" for a live GL turn, "daniela-consult" for a consult reply. */
  participant: 'daniela' | 'daniela-consult';
}

const DANIELA_LABEL = { 'daniela': '**Daniela:** ', 'daniela-consult': '**Daniela [consult]:** ' } as const;

/** The exact event a bench turn records, in the receipt and in the episode. */
export function benchEvent(turn: BenchTurn): AppendEvent {
  const frames: AppendEvent['frames'] = [{
    kind: 'attributed', frameKey: 'luca', label: '**Luca:** ', body: turn.lucaText,
    speaker: 'luca', hat: 'unknown', hatEvidence: 'none', captureId: null, provenance: null,
  }];
  if (turn.danielaText !== '') {
    frames.push({ kind: 'participant', frameKey: 'daniela', label: DANIELA_LABEL[turn.participant], body: turn.danielaText, participant: turn.participant });
  }
  return { source: BENCH_SOURCE, sourceEventId: benchEventId(turn.sessionId, turn.turnId), frames };
}

export type StoredTurn =
  | { status: 'none'; rowId: string | null }
  | { status: 'complete'; rowId: string; event: AppendEvent; lucaText: string; danielaText: string }
  | { status: 'conflict'; reason: string };

interface SessionRow { id: string; content: string; attribution: unknown; tags: string[] }

async function sessionRow(db: SqlExecutor, sessionId: string, lock: boolean): Promise<SessionRow | null> {
  const query = lock
    ? sql`SELECT id, content, attribution, tags FROM conversation_memories WHERE ${sessionTag(sessionId)} = ANY(tags) ORDER BY created_at LIMIT 2 FOR UPDATE`
    : sql`SELECT id, content, attribution, tags FROM conversation_memories WHERE ${sessionTag(sessionId)} = ANY(tags) ORDER BY created_at LIMIT 2`;
  const rows = rowsOf(await db.execute(query));
  if (rows.length > 1) throw new Error(`bench session ${sessionId} has more than one receipt row`);
  const row = rows[0];
  if (!row) return null;
  return { id: row.id as string, content: (row.content as string) ?? '', attribution: row.attribution, tags: (row.tags as string[]) ?? [] };
}

/** Read the stored event of one turn from the database (never the in-memory Map). */
function storedEvent(row: SessionRow, sessionId: string, turnId: string): StoredTurn {
  const verdict = verifyTurnAttribution(row.content, turnAttributionOf(row.attribution));
  if (verdict.status === 'absent') return { status: 'none', rowId: row.id };
  if (verdict.status === 'invalid') return { status: 'conflict', reason: `session receipt does not verify: ${verdict.reason}` };
  const eventId = benchEventId(sessionId, turnId);
  const frames = verdict.frames.filter(f => f.source === BENCH_SOURCE && f.sourceEventId === eventId);
  if (frames.length === 0) return { status: 'none', rowId: row.id };
  const luca = frames.find(f => f.frameKey === 'luca');
  const daniela = frames.find(f => f.frameKey === 'daniela');
  if (!luca) return { status: 'conflict', reason: `turn ${turnId} receipt lacks its luca frame` };
  const event: AppendEvent = {
    source: BENCH_SOURCE, sourceEventId: eventId,
    frames: frames.map(f => f.kind === 'participant'
      ? { kind: 'participant', frameKey: f.frameKey, label: f.label, body: f.body, participant: f.participant }
      : { kind: 'attributed', frameKey: f.frameKey, label: f.label, body: f.body, speaker: f.speaker, hat: f.hat, hatEvidence: f.hat === 'unknown' ? 'none' : 'authenticated-actor', captureId: f.captureId, provenance: null }),
  };
  return { status: 'complete', rowId: row.id, event, lucaText: luca.body, danielaText: daniela?.body ?? '' };
}

/**
 * Before running Daniela: has this turn already completed? A complete turn
 * whose stored Luca bytes differ from the incoming request, or a session
 * owned by another user, is a conflict (fail closed).
 */
export async function findBenchTurn(db: SqlExecutor, sessionId: string, turnId: string, userId: string, lucaText: string): Promise<StoredTurn> {
  const row = await sessionRow(db, sessionId, false);
  if (!row) return { status: 'none', rowId: null };
  if (!row.tags.includes(ownerTag(userId))) return { status: 'conflict', reason: 'bench session belongs to another user' };
  const stored = storedEvent(row, sessionId, turnId);
  if (stored.status === 'complete' && stored.lucaText !== lucaText) {
    return { status: 'conflict', reason: `turn ${turnId} was already recorded with different text` };
  }
  return stored;
}

export interface SessionMeta { userId: string; topicHint: string; dateStr: string }

/** The legacy header every bench session row starts with (unchanged bytes). */
export function sessionHeader(topicHint: string): string {
  return [topicHint ? `With Luca — ${topicHint}` : 'With Luca', '', '---'].join('\n');
}

export type RecordResult =
  | { kind: 'stored' | 'exact-retry'; rowId: string }
  | { kind: 'conflict'; reason: string };

/**
 * Persist one turn's receipt, atomically, before any episode dispatch.
 * A transaction-scoped advisory lock on the session identity serializes
 * first-turn creation across connections and processes, so two concurrent
 * first turns cannot create two rows; the row lock in the common append
 * serializes concurrent appends.
 */
export async function recordBenchTurn(db: TransactionalDb, turn: BenchTurn, meta: SessionMeta): Promise<RecordResult> {
  const event = benchEvent(turn);
  return db.transaction(async tx => {
    await tx.execute(sql`SELECT pg_advisory_xact_lock(hashtextextended(${sessionTag(turn.sessionId)}, 0))`);
    let row = await sessionRow(tx, turn.sessionId, true);
    if (row && !row.tags.includes(ownerTag(meta.userId))) return { kind: 'conflict', reason: 'bench session belongs to another user' };
    if (!row) {
      const title = `Luca ↔ Daniela — ${meta.topicHint || 'Voice Session'} — ${meta.dateStr}`;
      const tags = ['agent-daniela', 'agent-voice-turn', 'luca-daniela', 'verbatim', IN_PROGRESS_TAG, sessionTag(turn.sessionId), ownerTag(meta.userId)];
      const inserted = rowsOf(await tx.execute(sql`
        INSERT INTO conversation_memories (id, title, summary, content, participants, tags, importance, created_at, entry_type, arc_name)
        VALUES (gen_random_uuid(), ${title}, ${'Verbatim Luca↔Daniela voice session — recorded per turn.'}, ${sessionHeader(meta.topicHint)},
                ARRAY['Luca', 'Daniela']::text[], ${textArray(tags)}, 8, NOW(), 'conversation', 'agent-daniela')
        RETURNING id
      `))[0];
      row = { id: inserted.id as string, content: '', attribution: null, tags };
    }
    const applied = await applyProjectionAppendInTx(tx, row.id, event);
    if (applied.kind === 'append') return { kind: 'stored', rowId: row.id };
    if (applied.kind === 'noop') return { kind: 'exact-retry', rowId: row.id };
    if (applied.kind === 'missing') return { kind: 'conflict', reason: 'session receipt row vanished inside its transaction' };
    return { kind: 'conflict', reason: applied.reason };
  });
}

export type ProjectionResult = 'appended' | 'already-present' | 'no-rolling-episode' | { conflict: string };

/**
 * Project a stored turn into the rolling episode through the common append.
 * Called after the receipt commits, and again on every exact retry: finding
 * the receipt is never treated as proof the episode already has the turn,
 * so a projection that failed earlier is repaired here.
 */
export async function projectBenchTurn(db: TransactionalDb, event: AppendEvent, rollingEpisodeId: (tx: SqlExecutor) => Promise<string | null>): Promise<ProjectionResult> {
  return db.transaction(async tx => {
    const episodeId = await rollingEpisodeId(tx);
    if (!episodeId) return 'no-rolling-episode' as const;
    const applied = await applyProjectionAppendInTx(tx, episodeId, event);
    if (applied.kind === 'append') return 'appended' as const;
    if (applied.kind === 'noop') return 'already-present' as const;
    if (applied.kind === 'missing') return 'no-rolling-episode' as const;
    return { conflict: applied.reason };
  });
}

/** Does this session already record receipts? (A mixed session is refused.) */
export async function benchSessionExists(db: SqlExecutor, sessionId: string): Promise<boolean> {
  return (await sessionRow(db, sessionId, false)) !== null;
}

/**
 * endSession / expiry: finalize the SAME row (title, tags), never insert a
 * second transcript. Returns the row id, or null when this session has no
 * receipt row (a legacy session, which keeps the legacy insert).
 */
export async function finalizeBenchSession(db: SqlExecutor, sessionId: string, title: string | null, extraTags: string[]): Promise<string | null> {
  const row = rowsOf(await db.execute(sql`
    UPDATE conversation_memories
    SET title = COALESCE(${title}, title),
        tags = ARRAY(SELECT DISTINCT t FROM unnest(array_remove(tags, ${IN_PROGRESS_TAG}) || ${textArray(extraTags)}) AS t)
    WHERE ${sessionTag(sessionId)} = ANY(tags)
    RETURNING id
  `))[0];
  return typeof row?.id === 'string' ? row.id : null;
}

/** Unfinished receipt rows older than the cutoff (restart-safe expiry). */
export async function staleBenchSessions(db: SqlExecutor, olderThan: Date): Promise<string[]> {
  const rows = rowsOf(await db.execute(sql`
    SELECT tags FROM conversation_memories
    WHERE ${IN_PROGRESS_TAG} = ANY(tags) AND 'agent-voice-turn' = ANY(tags) AND created_at < ${olderThan.toISOString()}::timestamptz
  `));
  return rows.flatMap(r => ((r.tags as string[]) ?? []).filter(t => t.startsWith('bench-session:')).map(t => t.slice('bench-session:'.length)));
}

/**
 * In-process reservation of one bench turn (luca-replit review of PR69, R1).
 * The check and the reservation are ONE synchronous step, taken before the
 * route's first await, so two concurrent identical requests in this process
 * cannot both reach the model. Returns the owner's release, or null when the
 * turn is already reserved. Release removes only this owner's reservation, and
 * the route calls it when the attempt has actually finished (never on an HTTP
 * disconnect). Cross-process duplicates are still decided by the receipt's
 * first write.
 */
export function reserveBenchTurn(inFlight: Map<string, symbol>, key: string): (() => void) | null {
  if (inFlight.has(key)) return null;
  const owner = Symbol(key);
  inFlight.set(key, owner);
  return () => { if (inFlight.get(key) === owner) inFlight.delete(key); };
}
